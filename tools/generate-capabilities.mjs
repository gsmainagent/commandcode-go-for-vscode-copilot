/**
 * Generate `src/capabilities.ts` from the Command Code plan page.
 *
 * `https://commandcode.ai/docs/plans/<plan>` states, per model, what the plan
 * includes and what the model can do. The capabilities live in the `Caps`
 * column as an aria-label, e.g.
 *
 *     aria-label="Capabilities: Text input, Vision, Reasoning"
 *
 * That is the vendor's own statement, so it is the source of truth here.
 *
 * Why not probe instead: an earlier version of this file measured each model by
 * sending it a solid-red image, and got 10 vision-capable models wrong — every
 * Kimi among them. The cause was a transport mismatch: probes went through an
 * OpenAI-compatible proxy that does not forward image parts, so every model
 * looked text-only. Re-probing over the correct endpoint fixed the symptom but
 * kept the weakness: a single sample per model is weaker evidence than the
 * vendor's declaration, and it costs several requests per model. The plan page
 * costs one request and states the same thing outright.
 *
 * Usage:
 *   node tools/generate-capabilities.mjs
 *   node tools/generate-capabilities.mjs --plan pro --out src/capabilities.ts
 *
 * Options:
 *   --plan <slug>     plan page to read (default: go)
 *   --out <path>      output file (default: src/capabilities.ts)
 *
 * Writes only the generated file. The runtime still parses the page itself
 * (see `src/plan-catalog.ts`), so this script only needs to run when the table
 * changes — which the `cc-goplan-watch` cron already watches for.
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

const args = process.argv.slice(2);
const flag = (name, fallback) => {
	const i = args.indexOf(`--${name}`);
	return i >= 0 && args[i + 1] ? args[i + 1] : fallback;
};

const PLAN = flag('plan', 'go');
const OUT = path.resolve(ROOT, flag('out', path.join('src', 'capabilities.ts')));
const URL_BASE = 'https://commandcode.ai/docs/plans';
const PLAN_URL = `${URL_BASE}/${encodeURIComponent(PLAN)}`;

/**
 * A table yielding fewer models than this is treated as a layout change, not a
 * shrunken plan — writing it would silently mark models text-only.
 */
const MIN_ROWS = 20;

const stripTags = (html) =>
	html
		.replace(/<svg\b[\s\S]*?<\/svg>/g, ' ')
		.replace(/<[^>]+>/g, ' ')
		.replace(/&amp;/g, '&')
		.replace(/&nbsp;/g, ' ')
		.replace(/\s+/g, ' ')
		.trim();

/** Compare model ids across sources: `hy3-paid` and `tencent-hy3` are one model. */
const slugify = (value) => {
	let out = String(value).toLowerCase();
	for (const char of ['.', '/', '_', ':', '+']) out = out.replaceAll(char, '-');
	while (out.includes('--')) out = out.replaceAll('--', '-');
	return out.replace(/^-+|-+$/g, '');
};

const billingVariants = (key) =>
	['-paid', '-free', '-usd', '-credits']
		.filter((suffix) => key.endsWith(suffix))
		.map((suffix) => key.slice(0, -suffix.length));

/** Pull one model row out of the table. */
function parseRow(rowHtml) {
	const slug = /\/models\/([a-z0-9][a-z0-9.-]*)/i.exec(rowHtml)?.[1];
	if (!slug) return null;

	const capsLabel = /aria-label="Capabilities:\s*([^"]*)"/i.exec(rowHtml)?.[1]?.trim();

	let name = '';
	let contextLength;
	for (const cell of rowHtml.match(/<td\b[\s\S]*?<\/td>/gi) ?? []) {
		const text = stripTags(cell);
		if (!text) continue;
		if (!name && /\/models\//.test(cell)) {
			name = text;
			continue;
		}
		if (contextLength === undefined && /text-right/.test(cell)) {
			const size = /^(\d+(?:\.\d+)?)\s*([KM])?$/i.exec(text);
			if (size) {
				const n = Number(size[1]);
				const unit = (size[2] ?? '').toUpperCase();
				contextLength = Math.round(n * (unit === 'M' ? 1e6 : unit === 'K' ? 1e3 : 1));
			}
		}
	}

	const lower = (capsLabel ?? '').toLowerCase();
	return {
		slug: slug.toLowerCase(),
		name: name || slug,
		// `undefined` means the row carried no Caps label, which is different
		// from a label that omits Vision.
		vision: capsLabel === undefined ? undefined : lower.includes('vision'),
		reasoning: capsLabel === undefined ? undefined : lower.includes('reasoning'),
		contextLength,
	};
}

function renderTable(entries, probeDate, plan) {
	const lines = [
		'// Generated by tools/generate-capabilities.mjs — do not edit by hand.',
		'//',
		`// Source: the \`Caps\` column of ${URL_BASE}/${plan}, which states each model's`,
		'// capabilities verbatim in an aria-label, e.g.',
		'// `Capabilities: Text input, Vision, Reasoning`.',
		'//',
		'// This is the vendor\'s own statement, so it wins over inference. An earlier build',
		'// measured capabilities by probing models through an OpenAI-compatible proxy,',
		'// which does not forward image parts — that marked 10 vision-capable models as',
		'// text-only (every Kimi among them) and disagreed on reasoning for 14 more.',
		'//',
		'// The runtime reads the same page (see `src/plan-catalog.ts`), so this file only',
		'// covers models the picker would otherwise have to guess about. Models absent',
		'// here fall back to CONSERVATIVE_CAPABILITIES.',
		`//`,
		`// Generated from the ${plan} plan on ${probeDate}.`,
		'',
		'/**',
		' * Default capabilities for a model with no vendor-declared entry.',
		' *',
		' * Vision is off on purpose: an unknown model that silently drops images is a',
		' * smaller problem than a text-only model being handed image bytes. Tools stay on',
		' * because every callable model in the measured set supported them.',
		' */',
		'export const CONSERVATIVE_CAPABILITIES = {',
		'\tvision: false,',
		'\tthinking: true,',
		'} as const;',
		'',
		'/**',
		' * Vendor-declared capabilities, keyed by catalog model id.',
		' *',
		' * `vision` comes from the plan page listing Vision in the model\'s Caps column;',
		' * `thinking` likewise for Reasoning. Context windows are deliberately absent:',
		' * they come from the live catalog at runtime, which is always newer than this file.',
		' */',
		'export const MEASURED_CAPABILITIES: Readonly<Record<string, MeasuredCapability>> = {',
		...entries.map(
			({ id, vision, reasoning }) =>
				`\t'${id}': { vision: ${String(vision).toLowerCase()}, thinking: ${String(reasoning).toLowerCase()} },`,
		),
		'};',
		'',
		'export interface MeasuredCapability {',
		'\t/** Vendor-declared vision support. */',
		'\treadonly vision: boolean;',
		'\t/** Vendor-declared reasoning support. */',
		'\treadonly thinking: boolean;',
		'}',
		'',
		'/**',
		' * Look up vendor-declared capabilities for a catalog model id.',
		' */',
		'export function measuredCapabilities(modelId: string): MeasuredCapability | undefined {',
		'\treturn MEASURED_CAPABILITIES[modelId];',
		'}',
		'',
	];
	return lines.join('\n');
}

(async () => {
	console.log(`fetching ${PLAN_URL}`);
	const response = await fetch(PLAN_URL, { headers: { Accept: 'text/html' } });
	if (!response.ok) {
		console.error(`HTTP ${response.status} from ${PLAN_URL}`);
		process.exit(1);
	}

	const html = await response.text();
	const table = /<table\b[\s\S]*?<\/table>/i.exec(html)?.[0];
	if (!table) {
		console.error('no <table> found; the page layout likely changed');
		process.exit(1);
	}

	const rows = [];
	for (const rowHtml of table.match(/<tr\b[\s\S]*?<\/tr>/gi) ?? []) {
		const parsed = parseRow(rowHtml);
		if (parsed) rows.push(parsed);
	}

	if (rows.length < MIN_ROWS) {
		console.error(
			`parsed ${rows.length} rows (< ${MIN_ROWS}); refusing to write a table that would ` +
				'mark most models text-only',
		);
		process.exit(1);
	}

	// The docs identify models by slug; the picker needs the id the Generate API
	// expects. The two differ only in punctuation and in billing qualifiers
	// (`tencent-hy3` on the page, `tencent/hy3-paid` in the catalog), and the API
	// catalog is the only source of canonical ids.
	const CATALOG_URL = 'https://api.commandcode.ai/provider/v1/models';
	let knownIds = [];
	try {
		const catalogResponse = await fetch(CATALOG_URL);
		const catalog = await catalogResponse.json();
		knownIds = (catalog.data ?? []).map((m) => m.id).filter(Boolean);
	} catch (error) {
		console.warn(`could not read ${CATALOG_URL}: ${error.message}`);
	}

	const byKey = new Map();
	const remember = (key, id) => {
		if (!byKey.has(key)) byKey.set(key, id);
	};
	for (const id of knownIds) {
		for (const key of new Set([slugify(id.split('/').pop() ?? id), slugify(id)])) {
			remember(key, id);
			for (const variant of billingVariants(key)) remember(variant, id);
		}
	}

	const entries = [];
	const unmatched = [];
	for (const row of rows) {
		const id = byKey.get(slugify(row.slug));
		if (!id) {
			unmatched.push(row.slug);
			continue;
		}
		// A row without a Caps label tells us nothing; keep the conservative
		// default rather than asserting `false`.
		if (row.vision === undefined) continue;
		entries.push({ id, vision: row.vision, reasoning: Boolean(row.reasoning) });
	}

	fs.writeFileSync(OUT, renderTable(entries, new Date().toISOString().slice(0, 10), PLAN));

	console.log(`wrote ${OUT}`);
	console.log(`  rows parsed : ${rows.length}`);
	console.log(`  entries     : ${entries.length} (vision ${entries.filter((e) => e.vision).length})`);
	if (unmatched.length) {
		console.log(`  unmatched   : ${unmatched.length} ${unmatched.join(', ')}`);
	}
	if (!entries.length) {
		console.error('no entries resolved; leaving the existing file untouched would be safer');
		process.exit(1);
	}
})().catch((error) => {
	console.error(error);
	process.exitCode = 1;
});